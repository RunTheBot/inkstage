import assert from 'node:assert/strict';
import { WebSocket } from 'ws';
import { writeFile, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import JSZip from 'jszip';
import { demoDeck } from '../server/demo.mjs';
import { inspectDeck, renderDeck } from '../server/deck.mjs';
import { getDocument, OPS } from 'pdfjs-dist/legacy/build/pdf.mjs';

const origin = process.env.INKSTAGE_TEST_URL ?? 'http://localhost:4173';
const fixture = await JSZip.loadAsync(await demoDeck());
fixture.file('ppt/slides/slide2.xml', (await fixture.file('ppt/slides/slide2.xml').async('string')).replace(/<p:sld\b/, '<p:sld show="0"'));
const original = await fixture.generateAsync({ type: 'nodebuffer' });
const form = new FormData(); form.append('deck', new Blob([original]), 'Integration test.pptx');
console.log('Importing a real PPTX through the upload endpoint and PowerPoint renderer…');
const imported = await fetch(`${origin}/api/sessions`, { method: 'POST', body: form });
const credential = await imported.json(); assert.equal(imported.status, 201, JSON.stringify(credential));
const auth = { Authorization: `Bearer ${credential.token}` };
const state = await (await fetch(`${origin}/api/sessions/${credential.id}`, { headers: auth })).json();
assert.equal(state.slides.length, 4); assert.ok(state.slides[0].notes);
assert.equal((await fetch(`${origin}/api/sessions/${credential.id}`)).status, 403);
const links = await (await fetch(`${origin}/api/sessions/${credential.id}/links`, { headers: auth })).json();
const image = await fetch(`${origin}/api/sessions/${credential.id}/slides/slide-1.png?role=audience&token=${links.tokens.audience}`);
assert.equal(image.status, 200); assert.equal(image.headers.get('content-type'), 'image/png');
assert.equal((await fetch(`${origin}/api/sessions/${credential.id}/slides.pdf`)).status, 403);
const vectorResponse = await fetch(`${origin}/api/sessions/${credential.id}/slides.pdf`, { headers: { Authorization: `Bearer ${links.tokens.audience}`, 'X-Inkstage-Role': 'audience' } });
assert.equal(vectorResponse.status, 200); assert.equal(vectorResponse.headers.get('content-type'), 'application/pdf');
const pdf = await getDocument({ data: new Uint8Array(await vectorResponse.arrayBuffer()) }).promise;
assert.equal(pdf.numPages, 4, 'PDF must retain hidden slides so page indices match the deck');
let fullText = '';
for (let i = 1; i <= pdf.numPages; i++) {
  const page = await pdf.getPage(i), text = await page.getTextContent(), operators = await page.getOperatorList();
  assert.ok(text.items.length > 0, 'Slide text must remain text, not a full-page bitmap');
  assert.ok(operators.fnArray.includes(OPS.constructPath), 'Slide drawings must retain vector paths');
  fullText += text.items.map(item => item.str ?? '').join(' ');
}
for (const slide of state.slides) if (slide.notes) assert.ok(!fullText.includes(slide.notes), 'Audience PDF must not include speaker notes');
await pdf.loadingTask.destroy();
console.log('PDF: vector text and drawings preserved; hidden slide order and notes privacy verified.');
const clients = [];
async function connect(role) {
  const ws = new WebSocket(`${origin.replace('http', 'ws')}/ws?session=${credential.id}&role=${role}&token=${links.tokens[role]}`);
  const messages = [], waiters = [];
  ws.on('message', data => { const msg = JSON.parse(data.toString()); messages.push(msg); for (const waiter of [...waiters]) if (waiter.predicate(msg)) { waiters.splice(waiters.indexOf(waiter), 1); clearTimeout(waiter.timer); waiter.resolve(msg); } });
  const wait = predicate => {
    const existing = messages.find(predicate); if (existing) return Promise.resolve(existing);
    return new Promise((resolve, reject) => { const waiter = { predicate, resolve, timer: setTimeout(() => reject(new Error('WebSocket event timeout')), 7000) }; waiters.push(waiter); });
  };
  const snapshot = await wait(m => m.type === 'snapshot');
  clients.push(ws); return { ws, wait, snapshot };
}
try {
  const presenter = await connect('presenter'), pen = await connect('pen'), audience = await connect('audience');
  assert.equal(audience.snapshot.state.slides[0].notes, '');
  const stroke = { id: 'integration_stroke_01', tool: 'pen', color: '#e4594e', width: 5, points: [{ x: .1, y: .55 }] };
  let started = performance.now();
  pen.ws.send(JSON.stringify({ type: 'stroke-start', slide: 0, stroke }));
  await Promise.all([presenter.wait(m => m.type === 'stroke-start'), audience.wait(m => m.type === 'stroke-start')]);
  console.log(`Ink relayed to presenter + audience in ${(performance.now() - started).toFixed(1)} ms on loopback.`);
  pen.ws.send(JSON.stringify({ type: 'stroke-points', slide: 0, id: stroke.id, points: [{ x: .35, y: .6 }, { x: .6, y: .54 }] }));
  await audience.wait(m => m.type === 'stroke-points');
  pen.ws.send(JSON.stringify({ type: 'stroke-replace', slide: 0, id: stroke.id, points: [stroke.points[0], { x: .7, y: .55 }] }));
  await audience.wait(m => m.type === 'stroke-replace');
  pen.ws.send(JSON.stringify({ type: 'stroke-start', slide: 0, stroke: { ...stroke, id: 'transient_finger_stroke' } }));
  await audience.wait(m => m.type === 'stroke-start' && m.stroke.id === 'transient_finger_stroke');
  pen.ws.send(JSON.stringify({ type: 'stroke-cancel', slide: 0, id: 'transient_finger_stroke', op: 'pinch-cancel-test' }));
  assert.equal((await audience.wait(m => m.type === 'ink-state' && m.op === 'pinch-cancel-test')).strokes.length, 1);
  audience.ws.send(JSON.stringify({ type: 'navigate', current: 2 }));
  await audience.wait(m => m.type === 'error');
  pen.ws.send(JSON.stringify({ type: 'erase', slide: 0, ids: [stroke.id], op: 'erase-test' }));
  assert.equal((await audience.wait(m => m.type === 'ink-state' && m.op === 'erase-test')).strokes.length, 0);
  pen.ws.send(JSON.stringify({ type: 'undo', slide: 0, op: 'undo-test' }));
  assert.equal((await audience.wait(m => m.type === 'ink-state' && m.op === 'undo-test')).strokes[0].points.length, 2);
  presenter.ws.send(JSON.stringify({ type: 'navigate', current: 2 }));
  await audience.wait(m => m.type === 'controls' && m.current === 2);
  presenter.ws.send(JSON.stringify({ type: 'blackout', value: true }));
  await audience.wait(m => m.type === 'controls' && m.blackout);
  presenter.ws.send(JSON.stringify({ type: 'blackout', value: false }));
  presenter.ws.send(JSON.stringify({ type: 'timer', action: 'start' }));
  await audience.wait(m => m.type === 'controls' && m.timer.running);
  const reconnect = await connect('audience');
  assert.equal(reconnect.snapshot.state.current, 2);
  assert.equal(reconnect.snapshot.state.strokes[0][0].points.length, 2);
  const pressureStroke = { id: 'integration_pressure_01', tool: 'pen', color: '#4077d1', width: 12, sensitivity: .8, points: [{ x: .1, y: .8, pressure: .1 }] };
  pen.ws.send(JSON.stringify({ type: 'stroke-start', slide: 2, stroke: pressureStroke }));
  pen.ws.send(JSON.stringify({ type: 'stroke-points', slide: 2, id: pressureStroke.id, points: [{ x: .4, y: .8, pressure: .9 }, { x: .7, y: .8, pressure: .3 }] }));
  const pressureEvent = await audience.wait(m => m.type === 'stroke-points' && m.id === pressureStroke.id);
  assert.equal(pressureEvent.points[0].pressure, .9);
  const exported = await fetch(`${origin}/api/sessions/${credential.id}/export`, { headers: auth }); assert.equal(exported.status, 200);
  const out = Buffer.from(await exported.arrayBuffer());
  assert.equal((await inspectDeck(out)).slides.length, 4);
  const zip = await JSZip.loadAsync(out); assert.match(await zip.file('ppt/slides/slide1.xml').async('string'), /Inkstage pen/);
  assert.match(await zip.file('ppt/slides/slide3.xml').async('string'), /fill="norm" stroke="0"/);
  const testDir = path.resolve(process.env.INKSTAGE_TEST_OUTPUT ?? path.join(os.tmpdir(), 'inkstage-integration'));
  await mkdir(testDir, { recursive: true });
  await writeFile(path.join(testDir, 'annotated.pptx'), out);
  await writeFile(path.join(testDir, 'session.json'), JSON.stringify(credential));
  console.log('Reopening the exported PPTX in PowerPoint and rendering it…');
  await renderDeck(path.join(testDir, 'annotated.pptx'), path.join(testDir, 'rendered'));
  console.log(`PASS: import, auth, three-view live ink, line replacement, eraser, undo, navigation, blackout, timer, late join and PowerPoint export reopen. Rendered export: ${testDir}`);
} finally { for (const ws of clients) ws.close(); }
